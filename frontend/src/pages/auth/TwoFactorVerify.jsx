import React, { useState } from 'react';
import { useNavigate, Link } from 'react-router-dom';

export default function TwoFactorVerify() {
  const navigate = useNavigate();
  const [loading, setLoading] = useState(false);
  const [code, setCode] = useState('');
  const [error, setError] = useState('');

  const handleVerify = (e) => {
    e.preventDefault();
    setError('');
    
    if (code.length < 6) {
      setError('Please enter the complete 6-digit code');
      return;
    }
    
    setLoading(true);
    setTimeout(() => {
      navigate('/student');
    }, 1000);
  };

  return (
    <div className="grid grid-cols-12 gap-4 lg:gap-6 w-full max-w-5xl items-stretch font-['Hanken_Grotesk',sans-serif]">
      {/* Branding Side */}
      <div
        className="hidden lg:flex col-span-5 rounded-[24px] p-8 lg:p-10 flex-col justify-between shadow-sm overflow-hidden relative"
        style={{
          background: 'rgba(255, 255, 255, 0.7)',
          backdropFilter: 'blur(12px)',
          WebkitBackdropFilter: 'blur(12px)',
          border: '1px solid rgba(165, 214, 167, 0.3)',
        }}
      >
        <div className="relative z-20">
          <div className="flex items-center gap-2.5 mb-8">
            <div className="w-10 h-10 bg-[#00522d] rounded-full flex items-center justify-center shadow-sm">
              <span className="material-symbols-outlined text-white text-xl" style={{ fontVariationSettings: "'FILL' 1" }}>
                eco
              </span>
            </div>
            <span className="text-2xl font-bold text-[#00522d] tracking-tight">Upcycle</span>
          </div>
          
          <h1 className="text-[38px] font-bold text-[#0d1e25] leading-[1.18] mb-4 tracking-[-0.02em]">
            Verify Your <br/><span className="text-[#00522d]">Identity</span>
          </h1>
          <p className="text-[17px] leading-[26px] text-[#556158] max-w-xs font-normal">
            Enter the 6-digit security code generated by your mobile authenticator app.
          </p>
        </div>
        
        {/* Security Badge */}
        <div className="relative z-20 bg-white/60 backdrop-blur-md p-4 rounded-2xl border border-[#bec9be]/40 flex items-center gap-3">
          <div className="w-9 h-9 rounded-xl bg-[#00522d]/10 text-[#00522d] flex items-center justify-center">
            <span className="material-symbols-outlined text-lg">enhanced_encryption</span>
          </div>
          <div>
            <p className="text-xs font-bold text-[#0d1e25]">Hardware 2FA Active</p>
            <p className="text-[11px] text-[#556158]">SHA-256 TOTP Protocol</p>
          </div>
        </div>

        {/* Abstract decoration */}
        <div className="absolute -bottom-10 -right-10 w-64 h-64 bg-[#00522d]/5 rounded-full blur-3xl pointer-events-none"></div>
      </div>

      {/* Main Content */}
      <div
        className="col-span-12 lg:col-span-7 bg-white rounded-[32px] p-8 sm:p-12 lg:p-12 shadow-lg flex flex-col justify-between border border-[#bec9be]/30"
      >
        <form onSubmit={handleVerify} className="space-y-6">
          <div>
            <h2 className="text-[28px] font-bold text-[#0d1e25] mb-2 tracking-tight">Two-Factor Challenge</h2>
            <p className="text-sm text-[#556158] mb-6 leading-relaxed">
              Open your authenticator app (Google Authenticator, Authy, etc.) and enter the current code for <strong>Upcycle</strong>.
            </p>
            
            {error && (
              <div className="p-3 mb-4 bg-[#ffdad6] text-[#ba1a1a] rounded-xl text-xs font-medium flex items-center gap-2">
                <span className="material-symbols-outlined text-sm">error</span>
                <span>{error}</span>
              </div>
            )}

            <div className="space-y-2">
              <label className="text-xs font-bold text-[#0d1e25] uppercase tracking-wider block">
                6-Digit Security Code
              </label>
              <input 
                type="text"
                maxLength={6}
                value={code}
                onChange={(e) => {
                  const val = e.target.value;
                  if (val === '' || /^\d+$/.test(val)) setCode(val);
                }}
                placeholder="000000"
                className="w-full text-center text-3xl font-mono font-bold tracking-[0.5em] py-4 px-6 bg-[#e7f6ff]/40 border border-[#bec9be]/50 rounded-2xl text-[#00522d] focus:outline-none focus:ring-2 focus:ring-[#00522d]/20 focus:border-[#00522d] focus:bg-white transition-all"
                autoFocus
              />
            </div>
          </div>

          <div className="pt-4 space-y-4">
            <button 
              type="submit"
              disabled={loading || code.length < 6}
              className="w-full py-4 px-8 bg-[#00522d] text-white font-semibold text-base rounded-full shadow-lg hover:bg-[#003d21] hover:scale-[1.01] active:scale-[0.99] transition-all flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed"
            >
              {loading ? (
                <span className="inline-block w-5 h-5 border-2 border-white border-t-transparent rounded-full animate-spin"></span>
              ) : (
                <>
                  <span>Verify and Log In</span>
                  <span className="material-symbols-outlined text-[18px]">arrow_forward</span>
                </>
              )}
            </button>

            <div className="flex items-center justify-between text-xs text-[#556158] pt-2">
              <Link to="/login" className="hover:text-[#00522d] transition-colors">
                Back to Sign In
              </Link>
              <Link to="/support" className="text-[#00522d] font-bold hover:underline">
                Lost your device?
              </Link>
            </div>
          </div>
        </form>
      </div>
    </div>
  );
}
